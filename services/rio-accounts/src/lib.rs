fn storage_error(error: StoreError) -> ApiError {
    ApiError(match error {
        StoreError::Invalid => StatusCode::BAD_REQUEST,
        StoreError::Revoked => StatusCode::UNAUTHORIZED,
        StoreError::Capacity => StatusCode::TOO_MANY_REQUESTS,
        StoreError::Unavailable => StatusCode::SERVICE_UNAVAILABLE,
        StoreError::Conflict => StatusCode::CONFLICT,
        StoreError::Forbidden => StatusCode::FORBIDDEN,
    })
}
fn expected_request_origin(request: &Request) -> bool {
    let Ok(host) = unique_header(request.headers(), "host") else {
        return false;
    };
    let authority = request.uri().authority().map(|value| value.as_str());
    let uri_matches = matches!(
        (request.uri().scheme_str(), authority),
        (None, None) | (Some("https"), Some("localhost:8088"))
    );
    // HTTP/2 carries :authority in the URI. If Host is also present, both must match.
    uri_matches
        && (host.is_some()
            || (request.version() == axum::http::Version::HTTP_2 && authority.is_some()))
        && host.is_none_or(|value| value == "localhost:8088")
}

async fn boundary(request: Request, next: Next) -> Response {
    let headers = request.headers();
    let accepted = expected_request_origin(&request)
        && !headers.contains_key("forwarded")
        && !headers.contains_key("x-forwarded-host")
        && !headers.contains_key("x-forwarded-proto")
        && !headers.contains_key("x-forwarded-for")
        && !headers.contains_key(header::AUTHORIZATION)
        && request
            .uri()
            .query()
            .map(|q| q.len() <= 4096)
            .unwrap_or(true)
        && (request.uri().path() == "/auth/callback" || request.uri().query().is_none());
    let mut response = if accepted {
        next.run(request).await
    } else {
        ApiError(StatusCode::BAD_REQUEST).into_response()
    };
    for (name, value) in [
        ("cache-control", "no-store"),
        ("pragma", "no-cache"),
        ("referrer-policy", "no-referrer"),
        ("x-content-type-options", "nosniff"),
        ("x-frame-options", "DENY"),
        (
            "content-security-policy",
            "default-src 'none'; script-src 'self'; style-src 'self'; connect-src 'self'; base-uri 'none'; frame-ancestors 'none'; form-action 'none'",
        ),
    ] {
        response
            .headers_mut()
            .insert(name, HeaderValue::from_static(value));
    }
    response
}

async fn start(State(state): State<AppState>, headers: HeaderMap) -> Result<Response, ApiError> {
    let now = Instant::now();
    let (challenge, pkce) = PkceCodeChallenge::new_random_sha256();
    let (url, csrf, nonce) = state
        .client
        .authorize_url(
            CoreAuthenticationFlow::AuthorizationCode,
            || CsrfToken::new(random_token()),
            || Nonce::new(random_token()),
        )
        .set_pkce_challenge(challenge)
        .url();
    let transaction = random_token();
    let mut store = state.store.lock().await;
    store.prune(now);
    if let Some(previous) = cookie(&headers, FLOW_COOKIE)? {
        if let Some(db) = &state.db {
            db.discard_login(hash(&previous))
                .await
                .map_err(storage_error)?;
        }
        store.flows.remove(&hash(&previous));
    }
    if store.flows.len() >= MAX_FLOWS {
        return Err(ApiError(StatusCode::TOO_MANY_REQUESTS));
    }
    if let Some(db) = &state.db {
        let previous_session = cookie(&headers, SESSION_COOKIE)?.map(|value| hash(&value));
        db.begin_login(hash(&transaction), hash(csrf.secret()), previous_session)
            .await
            .map_err(storage_error)?;
    } else if !cfg!(test) {
        return Err(ApiError(StatusCode::SERVICE_UNAVAILABLE));
    }
    store.flows.insert(
        hash(&transaction),
        Flow {
            state_hash: hash(csrf.secret()),
            nonce,
            pkce,
            started: now,
        },
    );
    let mut response = Redirect::to(url.as_str()).into_response();
    set_cookie(&mut response, FLOW_COOKIE, Some(&transaction))?;
    Ok(response)
}

#[derive(Deserialize)]
#[serde(deny_unknown_fields)]
struct Callback {
    code: Option<String>,
    state: Option<String>,
    error: Option<String>,
    iss: Option<String>,
    #[serde(rename = "session_state")]
    _session_state: Option<String>,
    #[serde(rename = "error_description")]
    _error_description: Option<String>,
    #[serde(rename = "error_uri")]
    _error_uri: Option<String>,
}
async fn callback(
    State(state): State<AppState>,
    headers: HeaderMap,
    RawQuery(query): RawQuery,
) -> Response {
    let result = finish_callback(&state, &headers, query.as_deref()).await;
    let mut response = match result {
        Ok(response) => response,
        Err(error) => error.into_response(),
    };
    if set_cookie(&mut response, FLOW_COOKIE, None).is_err() {
        return ApiError(StatusCode::INTERNAL_SERVER_ERROR).into_response();
    }
    response
}
async fn finish_callback(
    state: &AppState,
    headers: &HeaderMap,
    query: Option<&str>,
) -> Result<Response, ApiError> {
    let transaction = cookie(headers, FLOW_COOKIE)?.ok_or(ApiError(StatusCode::BAD_REQUEST))?;
    // Always burn the matching browser transaction, even for malformed or missing query fields.
    let parsed: Result<Callback, _> = serde_urlencoded::from_str(query.unwrap_or(""));
    let input_state = parsed
        .as_ref()
        .ok()
        .and_then(|p| p.state.as_deref())
        .unwrap_or("");
    // Burn the in-process nonce/PKCE holder even when durable storage is unavailable.
    let flow_result =
        state
            .store
            .lock()
            .await
            .consume_flow(&transaction, input_state, Instant::now());
    // Delete the matching durable fence before validating the state or exchanging a code.
    let permit = if let Some(db) = &state.db {
        Some(
            db.consume_login(hash(&transaction), hash(input_state))
                .await
                .map_err(storage_error)?,
        )
    } else {
        None
    };
    let flow = flow_result?;
    let params = parsed.map_err(|_| ApiError(StatusCode::BAD_REQUEST))?;
    if params.error.is_some() || params.iss.as_deref().is_some_and(|iss| iss != ISSUER) {
        return Err(ApiError(StatusCode::BAD_REQUEST));
    }
    let code = params
        .code
        .filter(|c| !c.is_empty() && c.len() <= 2048)
        .ok_or(ApiError(StatusCode::BAD_REQUEST))?;
    let _permit = state
        .exchanges
        .clone()
        .try_acquire_owned()
        .map_err(|_| ApiError(StatusCode::SERVICE_UNAVAILABLE))?;
    let tokens = state
        .client
        .exchange_code(AuthorizationCode::new(code))
        .set_pkce_verifier(flow.pkce)
        .request_async(&state.http)
        .await
        .map_err(|_| ApiError(StatusCode::BAD_REQUEST))?;
    let token = tokens.id_token().ok_or(ApiError(StatusCode::BAD_REQUEST))?;
    let verifier = state
        .client
        .id_token_verifier()
        .set_allowed_algs([CoreJwsSigningAlgorithm::RsaSsaPkcs1V15Sha256]);
    let account_id = verify_identity(token, &verifier, &flow.nonce)?;
    let claims = token
        .claims(&verifier, &flow.nonce)
        .map_err(|_| ApiError(StatusCode::BAD_REQUEST))?;
    if let Some(expected) = claims.access_token_hash() {
        let algorithm = token
            .signing_alg()
            .map_err(|_| ApiError(StatusCode::BAD_REQUEST))?;
        let key = token
            .signing_key(&verifier)
            .map_err(|_| ApiError(StatusCode::BAD_REQUEST))?;
        let actual = AccessTokenHash::from_token(tokens.access_token(), algorithm, key)
            .map_err(|_| ApiError(StatusCode::BAD_REQUEST))?;
        if &actual != expected {
            return Err(ApiError(StatusCode::BAD_REQUEST));
        }
    }
    // Provider tokens are dropped; a committed row grants only a synthetic own-account read.
    let session_token = random_token();
    if let Some(db) = &state.db {
        let permit = permit.ok_or(ApiError(StatusCode::SERVICE_UNAVAILABLE))?;
        db.replace_session(permit, account_id, hash(&session_token), random_token())
            .await
            .map_err(storage_error)?;
    } else {
        #[cfg(test)]
        {
            let now = Instant::now();
            let mut store = state.store.lock().await;
            store.prune(now);
            if let Some(old) = cookie(headers, SESSION_COOKIE)? {
                store.sessions.remove(&hash(&old));
            }
            if store.sessions.len() >= MAX_SESSIONS {
                return Err(ApiError(StatusCode::TOO_MANY_REQUESTS));
            }
            store.sessions.insert(
                hash(&session_token),
                Session {
                    account_id,
                    csrf: random_token(),
                    created: now,
                    touched: now,
                },
            );
        }
        #[cfg(not(test))]
        return Err(ApiError(StatusCode::SERVICE_UNAVAILABLE));
    }
    let mut response = Redirect::to("/").into_response();
    set_cookie(&mut response, SESSION_COOKIE, Some(&session_token))?;
    Ok(response)
}
fn verify_identity(
    token: &CoreIdToken,
    verifier: &CoreIdTokenVerifier<'_>,
    nonce: &Nonce,
) -> Result<&'static str, ApiError> {
    let claims = token
        .claims(verifier, nonce)
        .map_err(|_| ApiError(StatusCode::BAD_REQUEST))?;
    // The library deliberately does not validate azp. This client requires exact audience/azp.
    if claims.audiences().len() != 1
        || claims.audiences()[0].as_str() != CLIENT_ID
        || claims
            .authorized_party()
            .is_some_and(|azp| azp.as_str() != CLIENT_ID)
    {
        return Err(ApiError(StatusCode::BAD_REQUEST));
    }
    match claims.subject().as_str() {
        "11111111-1111-4111-8111-111111111111" => Ok("TST-alpha"),
        "22222222-2222-4222-8222-222222222222" => Ok("TST-beta"),
        _ => Err(ApiError(StatusCode::FORBIDDEN)),
    }
}
async fn me(State(state): State<AppState>, headers: HeaderMap) -> Result<Json<Value>, ApiError> {
    let token = cookie(&headers, SESSION_COOKIE)?.ok_or(ApiError(StatusCode::UNAUTHORIZED))?;
    let (account_id, csrf) = if let Some(db) = &state.db {
        let session = db.load_session(hash(&token)).await.map_err(storage_error)?;
        (session.account_id, session.csrf)
    } else {
        #[cfg(test)]
        {
            let session = state
                .store
                .lock()
                .await
                .session(&hash(&token), Instant::now())?;
            (session.account_id, session.csrf)
        }
        #[cfg(not(test))]
        return Err(ApiError(StatusCode::SERVICE_UNAVAILABLE));
    };
    Ok(Json(json!({"accountId":account_id, "csrfToken":csrf,
        "actorKind":"SYNTHETIC_DEV_ACTOR", "credentialControl":"VERIFIED_DEV_OIDC",
        "accountActive":false,"mode":"SYNTHETIC_ONLY","operativeAuthority":"NONE",
        "canOpenContact":false,"account1":"HOLD"})))
}
fn mutation_headers(headers: &HeaderMap) -> Result<&str, ApiError> {
    if unique_header(headers, "origin")? != Some(ORIGIN)
        || unique_header(headers, "content-type")? != Some("application/json")
    {
        return Err(ApiError(StatusCode::FORBIDDEN));
    }
    unique_header(headers, "x-csrf-token")?.ok_or(ApiError(StatusCode::FORBIDDEN))
}
async fn end_session(
    state: &AppState,
    headers: &HeaderMap,
    body: &Bytes,
    all: bool,
) -> Result<Response, ApiError> {
    let csrf = mutation_headers(headers)?;
    let value: Value =
        serde_json::from_slice(body).map_err(|_| ApiError(StatusCode::BAD_REQUEST))?;
    if value.as_object().is_none_or(|o| !o.is_empty()) {
        return Err(ApiError(StatusCode::BAD_REQUEST));
    }
    let token = cookie(headers, SESSION_COOKIE)?.ok_or(ApiError(StatusCode::UNAUTHORIZED))?;
    let key = hash(&token);
    if let Some(db) = &state.db {
        if all {
            db.logout_all(key, csrf).await.map_err(storage_error)?;
        } else {
            db.logout(key, csrf).await.map_err(storage_error)?;
        }
    } else {
        #[cfg(test)]
        {
            let mut store = state.store.lock().await;
            let session = store.session(&key, Instant::now())?;
            if hash(csrf) != hash(&session.csrf) {
                return Err(ApiError(StatusCode::FORBIDDEN));
            }
            if all {
                store
                    .sessions
                    .retain(|_, candidate| candidate.account_id != session.account_id);
            } else {
                store.sessions.remove(&key);
            }
        }
        #[cfg(not(test))]
        return Err(ApiError(StatusCode::SERVICE_UNAVAILABLE));
    }
    let mut response =
        Json(json!({"loggedOut":true, "providerLogout":"NOT_REQUESTED","mode":"SYNTHETIC_ONLY"}))
            .into_response();
    set_cookie(&mut response, SESSION_COOKIE, None)?;
    Ok(response)
}
async fn logout(
    State(state): State<AppState>,
    headers: HeaderMap,
    body: Bytes,
) -> Result<Response, ApiError> {
    end_session(&state, &headers, &body, false).await
}
async fn logout_all(
    State(state): State<AppState>,
    headers: HeaderMap,
    body: Bytes,
) -> Result<Response, ApiError> {
    end_session(&state, &headers, &body, true).await
}

