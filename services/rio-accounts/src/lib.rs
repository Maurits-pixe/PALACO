impl DevConfig {
    /// Read synthetic settings without logging secrets or connection strings.
    pub fn from_env() -> Result<Self, io::Error> {
        let mut config = Self::from_values(
            &std::env::var("RIO_DEV_MODE").unwrap_or_default(),
            &std::env::var("RIO_DEV_CLIENT_SECRET").unwrap_or_default(),
            &std::env::var("RIO_DEV_TLS_CERT").unwrap_or_default(),
            &std::env::var("RIO_DEV_TLS_KEY").unwrap_or_default(),
        )?;
        config.database_url = std::env::var("RIO_DEV_DATABASE_URL").unwrap_or_default();
        if config.database_url.is_empty() {
            return Err(io::Error::other(
                "synthetic database configuration required",
            ));
        }
        Ok(config)
    }
    fn from_values(mode: &str, secret: &str, cert: &str, key: &str) -> Result<Self, io::Error> {
        if mode != "SYNTHETIC_ONLY"
            || !(64..=128).contains(&secret.len())
            || !secret.bytes().all(|b| b.is_ascii_hexdigit())
            || cert.trim().is_empty()
            || key.trim().is_empty()
        {
            return Err(io::Error::other(
                "invalid synthetic development configuration",
            ));
        }
        Ok(Self {
            client_secret: secret.to_owned(),
            database_url: String::new(),
            tls_cert: cert.to_owned(),
            tls_key: key.to_owned(),
        })
    }
}

/// The allowlist runs before discovery, JWKS or token network I/O. No proxy or redirects.
#[derive(Clone)]
struct GuardedHttp(reqwest::Client);
impl<'c> AsyncHttpClient<'c> for GuardedHttp {
    type Error = io::Error;
    type Future = Pin<Box<dyn Future<Output = Result<HttpResponse, io::Error>> + Send + 'c>>;
    fn call(&'c self, request: HttpRequest) -> Self::Future {
        Box::pin(async move {
            guard_provider_request(request.method(), &request.uri().to_string())?;
            let (parts, request_body) = request.into_parts();
            let mut response = self
                .0
                .request(parts.method, parts.uri.to_string())
                .headers(parts.headers)
                .body(request_body)
                .send()
                .await
                .map_err(|_| io::Error::other("identity transport rejected"))?;
            const LIMIT: usize = 1024 * 1024;
            if response
                .content_length()
                .is_some_and(|length| length > LIMIT as u64)
            {
                return Err(io::Error::other("identity response too large"));
            }
            let status = response.status();
            let headers = response.headers().clone();
            let mut body = Vec::new();
            while let Some(chunk) = response
                .chunk()
                .await
                .map_err(|_| io::Error::other("identity response rejected"))?
            {
                if chunk.len() > LIMIT.saturating_sub(body.len()) {
                    return Err(io::Error::other("identity response too large"));
                }
                body.extend_from_slice(&chunk);
            }
            let mut result = HttpResponse::new(body);
            *result.status_mut() = status;
            *result.headers_mut() = headers;
            Ok(result)
        })
    }
}
fn guard_provider_request(method: &Method, uri: &str) -> Result<(), io::Error> {
    let allowed = match *method {
        Method::GET => uri == DISCOVERY_URL || uri == JWKS_URL,
        Method::POST => uri == TOKEN_URL,
        _ => false,
    };
    if allowed {
        Ok(())
    } else {
        Err(io::Error::other("identity endpoint rejected"))
    }
}

struct Flow {
    state_hash: Key,
    nonce: Nonce,
    pkce: PkceCodeVerifier,
    started: Instant,
}
#[cfg(test)]
#[derive(Clone)]
struct Session {
    account_id: &'static str,
    csrf: String,
    created: Instant,
    touched: Instant,
}
#[cfg(test)]
impl Session {
    fn live(&self, now: Instant) -> bool {
        now.duration_since(self.created) < SESSION_ABSOLUTE
            && now.duration_since(self.touched) < SESSION_IDLE
    }
}
#[derive(Default)]
struct Store {
    flows: HashMap<Key, Flow>,
    #[cfg(test)]
    sessions: HashMap<Key, Session>,
}
impl Store {
    fn prune(&mut self, now: Instant) {
        self.flows
            .retain(|_, f| now.duration_since(f.started) < FLOW_TTL);
        #[cfg(test)]
        self.sessions.retain(|_, s| s.live(now));
    }
    fn consume_flow(&mut self, cookie: &str, state: &str, now: Instant) -> Result<Flow, ApiError> {
        // Remove before every validation and every network operation: failure burns the matching flow.
        let flow = self
            .flows
            .remove(&hash(cookie))
            .ok_or(ApiError(StatusCode::BAD_REQUEST))?;
        if now.duration_since(flow.started) >= FLOW_TTL || flow.state_hash != hash(state) {
            return Err(ApiError(StatusCode::BAD_REQUEST));
        }
        Ok(flow)
    }
    #[cfg(test)]
    fn session(&mut self, key: &Key, now: Instant) -> Result<Session, ApiError> {
        self.prune(now);
        let s = self
            .sessions
            .get_mut(key)
            .ok_or(ApiError(StatusCode::UNAUTHORIZED))?;
        s.touched = now;
        Ok(s.clone())
    }
}

/// Verified provider metadata, bounded login material, and durable T03 session storage.
#[derive(Clone)]
pub struct AppState {
    client: OidcClient,
    http: GuardedHttp,
    store: Arc<Mutex<Store>>,
    db: Option<Arc<PgStore>>,
    exchanges: Arc<Semaphore>,
}
impl AppState {
    /// Fence a restored fixture before any service opens it. Primary databases are rejected.
    pub async fn recovery_fence(config: &DevConfig) -> Result<(), io::Error> {
        let url = reqwest::Url::parse(&config.database_url)
            .map_err(|_| io::Error::other("restore database configuration invalid"))?;
        if url.path() != "/rio_synthetic_restore" {
            return Err(io::Error::other(
                "recovery command requires isolated restore database",
            ));
        }
        // The storage connection applies the restore fence transaction before exposing a handle.
        let db = PgStore::connect_local(&config.database_url)
            .await
            .map_err(|_| io::Error::other("restore database unavailable"))?;
        db.health()
            .await
            .map_err(|_| io::Error::other("restore fence unavailable"))
    }
    /// Discover only the fixed synthetic IdP through the bounded, allowlisted transport.
    pub async fn discover(config: &DevConfig) -> Result<Self, io::Error> {
        if config.database_url.contains("rio_synthetic_restore") {
            return Err(io::Error::other(
                "restored database cannot serve browser sessions",
            ));
        }
        let db = Arc::new(
            PgStore::connect_local(&config.database_url)
                .await
                .map_err(|_| io::Error::other("synthetic database unavailable"))?,
        );
        let http = GuardedHttp(
            reqwest::Client::builder()
                .redirect(reqwest::redirect::Policy::none())
                .no_proxy()
                .timeout(Duration::from_secs(8))
                .build()
                .map_err(|_| io::Error::other("identity client unavailable"))?,
        );
        let issuer =
            IssuerUrl::new(ISSUER.to_owned()).map_err(|_| io::Error::other("issuer invalid"))?;
        let metadata = CoreProviderMetadata::discover_async(issuer, &http)
            .await
            .map_err(|_| io::Error::other("identity discovery rejected"))?;
        if metadata.issuer().as_str() != ISSUER
            || metadata.authorization_endpoint().as_str() != AUTH_URL
            || metadata.token_endpoint().map(|u| u.as_str()) != Some(TOKEN_URL)
            || metadata.jwks_uri().as_str() != JWKS_URL
        {
            return Err(io::Error::other("identity metadata rejected"));
        }
        let client = CoreClient::from_provider_metadata(
            metadata,
            ClientId::new(CLIENT_ID.to_owned()),
            Some(ClientSecret::new(config.client_secret.clone())),
        )
        .set_auth_uri(
            AuthUrl::new(AUTH_URL.to_owned()).map_err(|_| io::Error::other("auth URL invalid"))?,
        )
        .set_token_uri(
            TokenUrl::new(TOKEN_URL.to_owned())
                .map_err(|_| io::Error::other("token URL invalid"))?,
        )
        .set_redirect_uri(
            RedirectUrl::new(CALLBACK.to_owned())
                .map_err(|_| io::Error::other("callback invalid"))?,
        );
        Ok(Self {
            client,
            http,
            store: Arc::new(Mutex::new(Store::default())),
            db: Some(db),
            exchanges: Arc::new(Semaphore::new(8)),
        })
    }
}

#[derive(Clone, Copy)]
struct ApiError(StatusCode);
impl IntoResponse for ApiError {
    fn into_response(self) -> Response {
        (
            self.0,
            Json(json!({"error":"request_rejected","mode":"SYNTHETIC_ONLY"})),
        )
            .into_response()
    }
}
fn hash(value: &str) -> Key {
    Sha256::digest(value.as_bytes()).into()
}
fn random_token() -> String {
    let mut bytes = [0_u8; 32];
    OsRng.fill_bytes(&mut bytes);
    URL_SAFE_NO_PAD.encode(bytes)
}
fn unique_header<'a>(headers: &'a HeaderMap, name: &str) -> Result<Option<&'a str>, ApiError> {
    let mut values = headers.get_all(name).iter();
    let result = values
        .next()
        .map(|v| v.to_str().map_err(|_| ApiError(StatusCode::BAD_REQUEST)))
        .transpose()?;
    if values.next().is_some() {
        return Err(ApiError(StatusCode::BAD_REQUEST));
    }
    Ok(result)
}
fn cookie(headers: &HeaderMap, name: &str) -> Result<Option<String>, ApiError> {
    let mut result = None;
    for value in headers.get_all(header::COOKIE).iter() {
        let value = value
            .to_str()
            .map_err(|_| ApiError(StatusCode::BAD_REQUEST))?;
        for part in value.split(';') {
            let Some((key, value)) = part.trim().split_once('=') else {
                continue;
            };
            if key == name {
                if result.is_some()
                    || value.len() != 43
                    || !value
                        .bytes()
                        .all(|b| b.is_ascii_alphanumeric() || b == b'-' || b == b'_')
                {
                    return Err(ApiError(StatusCode::BAD_REQUEST));
                }
                result = Some(value.to_owned());
            }
        }
    }
    Ok(result)
}
fn set_cookie(response: &mut Response, name: &str, value: Option<&str>) -> Result<(), ApiError> {
    let text = match value {
        Some(value) => format!("{name}={value}; Secure; HttpOnly; SameSite=Lax; Path=/"),
        None => format!("{name}=; Secure; HttpOnly; SameSite=Lax; Path=/; Max-Age=0"),
    };
    let value =
        HeaderValue::from_str(&text).map_err(|_| ApiError(StatusCode::INTERNAL_SERVER_ERROR))?;
    response.headers_mut().append(header::SET_COOKIE, value);
    Ok(())
}

